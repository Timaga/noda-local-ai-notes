"use strict";
const { app, BrowserWindow, ipcMain, session } = require("electron");
const fs = require("node:fs"), path = require("node:path"), assert = require("node:assert/strict");
const { protectRenderer, isTrustedRenderer } = require("../../frontend/renderer_trust");
const out = path.resolve(process.argv[2] || "");
assert.ok(process.argv[2] && !fs.existsSync(out), "Use a fresh explicit output directory");
fs.mkdirSync(out, { recursive: true });
app.setPath("userData", path.join(out, "profile")); app.setPath("sessionData", path.join(out, "profile"));
app.disableHardwareAcceleration(); app.commandLine.appendSwitch("disable-background-networking");
const checks = [], opened = []; let win, network = 0, children = 0;
const watchdog = setTimeout(() => app.exit(2), 30000);
async function run() {
  await app.whenReady();
  session.defaultSession.webRequest.onBeforeRequest(({ url }, done) => {
    const local = /^(file|data|about):/.test(url); if (!local) network++; done({ cancel: !local });
  });
  const page = path.join(out, "trusted notes.html"), foreign = path.join(out, "foreign.html"), preload = path.join(out, "preload.cjs");
  fs.writeFileSync(page, "<!doctype html><title>Trusted synthetic page</title>");
  fs.writeFileSync(foreign, "<!doctype html><title>Foreign synthetic page</title>");
  fs.writeFileSync(preload, `const {contextBridge,ipcRenderer}=require('electron');contextBridge.exposeInMainWorld('trustProbe',{check:()=>ipcRenderer.invoke('trust-probe')});`);
  win = new BrowserWindow({ show: false, webPreferences: { preload, nodeIntegration: false, contextIsolation: true, sandbox: true } });
  protectRenderer(win, page, { openExternal: url => { opened.push(url); } });
  win.webContents.on("did-create-window", () => { children++; });
  ipcMain.handle("trust-probe", event => isTrustedRenderer(event, win));
  await win.loadFile(page);
  assert.equal(await win.webContents.executeJavaScript("window.trustProbe.check()"), true);
  checks.push("trusted local main-frame IPC succeeds");
  await win.webContents.executeJavaScript("location.hash='note';window.trustProbe.check()").then(result => assert.equal(result, true));
  checks.push("same-document anchors retain access");
  await win.webContents.executeJavaScript("window.open('https://example.invalid/note')");
  assert.deepEqual(opened, ["https://example.invalid/note"]); assert.equal(children, 0);
  checks.push("web links use the external opener without app windows");
  await win.webContents.executeJavaScript("window.open('file:///C:/Windows/System32/cmd.exe')");
  assert.equal(opened.length, 1); assert.equal(children, 0);
  checks.push("external executable URLs and privileged popups are blocked");
  const before = win.webContents.getURL();
  const navigation = new Promise(resolve => win.webContents.once("will-frame-navigate", resolve));
  await win.webContents.executeJavaScript("location.href='https://example.invalid/replacement'");
  await navigation;
  assert.equal(win.webContents.getURL(), before); assert.equal(opened.length, 2);
  checks.push("main-frame external navigation cannot replace the app");
  await win.loadFile(foreign);
  assert.equal(await win.webContents.executeJavaScript("window.trustProbe.check()"), false);
  await win.webContents.executeJavaScript("window.open('https://example.invalid/foreign')");
  assert.equal(opened.length, 2);
  checks.push("same-window foreign documents cannot invoke IPC or the external opener");
  await win.loadFile(page);
  assert.equal(await win.webContents.executeJavaScript("window.trustProbe.check()"), true);
  assert.equal(network, 0);
  checks.push("trusted reload works without external network requests");
  fs.writeFileSync(path.join(out, "results.json"), JSON.stringify({ status: "pass", checks, network, children, electron: process.versions.electron }, null, 2));
  clearTimeout(watchdog); win.destroy(); app.exit(0);
}
run().catch(error => { clearTimeout(watchdog); fs.writeFileSync(path.join(out, "failure.txt"), String(error.stack || error)); app.exit(1); });
